import { RULES, runRules } from "./rules";
import type { Finding, PrFile, PrInfo, Rule, Severity } from "./types";

export type Verdict = "needs-changes" | "review-carefully" | "looks-clean";

export interface ChecklistItem {
  rule: Rule["id"];
  title: string;
  check: string;
  passed: boolean;
  count: number;
  worst: Severity | null;
}

export interface Report {
  pr: PrInfo;
  findings: Finding[];
  checklist: ChecklistItem[];
  counts: Record<Severity, number>;
  verdict: Verdict;
}

export const VERDICT_LABEL: Record<Verdict, string> = {
  "needs-changes": "Needs changes",
  "review-carefully": "Review carefully",
  "looks-clean": "Looks clean",
};

export function buildReport(pr: PrInfo, files: PrFile[]): Report {
  const findings = runRules({ pr, files });
  const counts: Record<Severity, number> = { critical: 0, warning: 0, info: 0 };
  for (const f of findings) counts[f.severity]++;
  const checklist = RULES.map((r): ChecklistItem => {
    const mine = findings.filter((f) => f.rule === r.id);
    const worst = mine.find((f) => f.severity === "critical")?.severity ?? mine.find((f) => f.severity === "warning")?.severity ?? mine[0]?.severity ?? null;
    return { rule: r.id, title: r.title, check: r.check, passed: mine.every((f) => f.severity === "info"), count: mine.length, worst };
  });
  const verdict: Verdict = counts.critical > 0 ? "needs-changes" : counts.warning > 0 ? "review-carefully" : "looks-clean";
  return { pr, findings, checklist, counts, verdict };
}

/** Link to a line in the PR's head commit, or to the PR's file list if the head repo is gone. */
export function lineUrl(pr: PrInfo, file?: string, line?: number): string | null {
  if (!pr.url) return null;
  if (!file) return `${pr.url}/files`;
  if (!pr.headRepo || !pr.headSha) return `${pr.url}/files`;
  const path = file.split("/").map(encodeURIComponent).join("/");
  return `https://github.com/${pr.headRepo}/blob/${pr.headSha}/${path}${line ? `#L${line}` : ""}`;
}

/** "1 note", "2 notes". */
export function plural(n: number, word: string): string {
  return `${n} ${word}${n === 1 ? "" : "s"}`;
}

/** "2 critical, 1 warning, 0 notes". */
export function countsLine(c: Record<Severity, number>): string {
  return `${c.critical} critical, ${plural(c.warning, "warning")}, ${plural(c.info, "note")}`;
}

const ICON: Record<Severity, string> = { critical: "🔴", warning: "🟡", info: "🔵" };

/** Markdown ready to paste as a PR review comment. */
export function toMarkdown(report: Report): string {
  const { pr, checklist, findings, counts } = report;
  const out: string[] = [];
  out.push(`## ReviewLens: ${VERDICT_LABEL[report.verdict]}`);
  out.push("");
  out.push(`**${pr.title}** (#${pr.number}) · +${pr.additions} / -${pr.deletions} · ${plural(pr.changedFiles, "file")}`);
  out.push("");
  out.push("### Checklist");
  for (const c of checklist) out.push(`- [${c.passed ? "x" : " "}] ${c.check}${c.count ? ` (${c.count})` : ""}`);
  out.push("");
  if (findings.length === 0) {
    out.push("No issues found by the automated checks. A human review is still needed for logic and design.");
  } else {
    out.push(`### Findings (${countsLine(counts)})`);
    for (const f of findings) {
      const where = f.file ? ` \`${f.file}${f.line ? `:${f.line}` : ""}\`` : "";
      out.push(`- ${ICON[f.severity]}${where} ${f.message}`);
      if (f.snippet) out.push(`  \`${f.snippet.replace(/`/g, "'")}\``);
    }
  }
  out.push("");
  out.push("_Generated by ReviewLens: rule-based checks, not a substitute for reading the code._");
  return out.join("\n");
}
